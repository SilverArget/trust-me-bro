const fs = require('node:fs');
const path = require('node:path');
const {load, source} = require('./phase3-verify.cjs');

const game = load(source('WORKTREE'));
const rows = JSON.parse(game(`JSON.stringify((()=>{
  const out=[];
  for(let level=1;level<=SCENE_COUNT;level++)for(let part=1;part<=PART_COUNT;part++){
    const g=buildScene(level,part),coin=coinPos(SCENES[level-1],part),fans=selectFans(level,part);
    const dock=g.anchors.dock,dockX=typeof dock==='object'?dock.x:dock;
    const dockW=typeof dock==='object'?(dock.w??DOCK[1]-DOCK[0]):DOCK[1]-DOCK[0];
    const dockY=typeof dock==='object'?(dock.y??GROUND-48):GROUND-48;
    const dockH=typeof dock==='object'?(dock.h??48):48;
    const surfaces=solidSurfaces(g.surfaces);
    out.push({level,part,fans:fans.map((fan,index)=>{
      const supports=surfaces.filter(s=>fan.x+fan.w>s.x&&fan.x<s.x+s.w&&Math.abs(fan.y+fan.h-s.y)<=1);
      const fc={x:fan.x+fan.w/2,y:fan.y+fan.h/2},dist=p=>Math.hypot(fc.x-p.x,fc.y-p.y);
      const overlap=(a,b)=>a.x+a.w>b.x&&a.x<b.x+b.w&&a.y+a.h>b.y&&a.y<b.y+b.h;
      const flags=[];
      if(!supports.length)flags.push('fan not on any surface');
      if(dist({x:g.anchors.spawn??66,y:GROUND})<40)flags.push('fan within 40 px of spawn');
      if(overlap(fan,coin))flags.push('fan overlapping a coin');
      if(overlap(fan,{x:dockX,y:dockY,w:dockW,h:dockH}))flags.push('fan overlapping dock');
      return{index:index+1,x:fan.x,y:fan.y,w:fan.w,h:fan.h,
        surface:supports.map(s=>({id:s.surfaceId??null,kind:s.kind,x:s.x,y:s.y,w:s.w})),
        spawnDistance:dist({x:g.anchors.spawn??66,y:GROUND}),coinDistance:dist({x:coin.x+coin.w/2,y:coin.y+coin.h/2}),
        dockDistance:dist({x:dockX+dockW/2,y:dockY+dockH/2}),flags};
    })});
  }
  return out;
})())`));

const allFans=rows.flatMap(r=>r.fans.map(f=>({...f,level:r.level,part:r.part})));
const flagged=allFans.filter(f=>f.flags.length);
const fmt=n=>Number(n).toFixed(1);
const lines=[
  '# Fan denetimi', '',
  'Generated by `node 03-test/fan-denetimi.cjs` from the worktree game geometry.', '',
  'Distances are Euclidean center-to-point/center distances in game-space pixels; overlap uses axis-aligned fan, coin, and dock rectangles.', '',
  '## Totals', '',
  `- Level/part pairs scanned: ${rows.length}`,
  `- Pairs with active fans: ${rows.filter(r=>r.fans.length).length}`,
  `- Active fans: ${allFans.length}`,
  `- Flagged fans: ${flagged.length}`,
  `- Not on a surface: ${allFans.filter(f=>f.flags.includes('fan not on any surface')).length}`,
  `- Within 40 px of spawn: ${allFans.filter(f=>f.flags.includes('fan within 40 px of spawn')).length}`,
  `- Overlapping a coin: ${allFans.filter(f=>f.flags.includes('fan overlapping a coin')).length}`,
  `- Overlapping dock: ${allFans.filter(f=>f.flags.includes('fan overlapping dock')).length}`, '',
  '## All 186 level/part pairs', ''
];
for(const r of rows){
  lines.push(`### ${r.level}.${r.part}`, '');
  if(!r.fans.length){lines.push('_No active fans._', '');continue;}
  lines.push('| Fan | x | y | Surface | Spawn dist. | Coin dist. | Dock dist. | Flags |', '|---:|---:|---:|---|---:|---:|---:|---|');
  for(const f of r.fans){
    const surface=f.surface.length?f.surface.map(s=>`${s.kind} ${s.id||'(no id)'} @ ${fmt(s.x)},${fmt(s.y)} w=${fmt(s.w)}`).join('; '):'none';
    lines.push(`| ${f.index} | ${fmt(f.x)} | ${fmt(f.y)} | ${surface} | ${fmt(f.spawnDistance)} | ${fmt(f.coinDistance)} | ${fmt(f.dockDistance)} | ${f.flags.join('; ')||'—'} |`);
  }
  lines.push('');
}
lines.push('## Needs decision', '');
if(!flagged.length)lines.push('_None. No active fan is unsupported, spawn-adjacent, or overlapping a coin/dock._');
else for(const f of flagged)lines.push(`- ${f.level}.${f.part} fan ${f.index} @ (${fmt(f.x)}, ${fmt(f.y)}): ${f.flags.join('; ')}`);
lines.push('');
const output=path.join(__dirname,'2026-09-15-fan-denetimi.md');
fs.writeFileSync(output,lines.join('\n'),'utf8');
console.log(JSON.stringify({pairs:rows.length,pairsWithFans:rows.filter(r=>r.fans.length).length,fans:allFans.length,flagged:flagged.length,flags:{unsupported:allFans.filter(f=>f.flags.includes('fan not on any surface')).length,nearSpawn:allFans.filter(f=>f.flags.includes('fan within 40 px of spawn')).length,coinOverlap:allFans.filter(f=>f.flags.includes('fan overlapping a coin')).length,dockOverlap:allFans.filter(f=>f.flags.includes('fan overlapping dock')).length},output}));
